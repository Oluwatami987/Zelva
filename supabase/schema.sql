-- Run this in Supabase SQL Editor.
create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  email text not null unique check (char_length(email) <= 254),
  phone text null check (phone is null or char_length(phone) <= 30),
  source text not null default 'zelva-landing-page',
  created_at timestamptz not null default now()
);

alter table public.waitlist enable row level security;

-- Public visitors can submit signups but cannot read, update, or delete entries.
create policy "Anyone can sign up to waitlist"
on public.waitlist
for insert
to anon
with check (
  char_length(name) between 1 and 80
  and char_length(email) between 3 and 254
  and (phone is null or char_length(phone) <= 30)
);

-- Do not create a SELECT policy for anon. Read entries through the Supabase dashboard.
